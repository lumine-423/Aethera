"""Prepare an openly licensed temporary UI font and original diagnostic sound."""
from pathlib import Path
import hashlib
import json
import math
import struct
import urllib.request
import wave

ROOT = Path(__file__).resolve().parents[1]
FONT = ROOT/'assets'/'fonts'
AUDIO = ROOT/'assets'/'audio'
FONT_URL = 'https://raw.githubusercontent.com/google/fonts/main/ofl/notosanssc/NotoSansSC%5Bwght%5D.ttf'
LICENSE_URL = 'https://raw.githubusercontent.com/google/fonts/main/ofl/notosanssc/OFL.txt'

def fetch(url, target):
    if not target.exists():
        with urllib.request.urlopen(url, timeout=60) as response:
            target.write_bytes(response.read())

FONT.mkdir(parents=True, exist_ok=True)
AUDIO.mkdir(parents=True, exist_ok=True)
fetch(FONT_URL, FONT/'NotoSansSC.ttf')
fetch(LICENSE_URL, FONT/'OFL.txt')
license_text = (FONT/'OFL.txt').read_text(encoding='utf-8')
if 'SIL OPEN FONT LICENSE' not in license_text:
    raise RuntimeError('Unexpected font license; do not use asset')
with wave.open(str(AUDIO/'probe-confirm.wav'), 'wb') as sound:
    sound.setparams((1,2,22050,0,'NONE','not compressed'))
    samples = []
    duration = 0.09
    for i in range(round(22050*duration)):
        t = i/22050
        envelope = math.sin(math.pi*t/duration)**2
        samples.append(struct.pack('<h', round(6000*envelope*math.sin(2*math.pi*660*t))))
    sound.writeframes(b''.join(samples))
receipt = {'font':{'url':FONT_URL,'license_url':LICENSE_URL,'license':'SIL Open Font License 1.1',
    'sha256':hashlib.file_digest((FONT/'NotoSansSC.ttf').open('rb'),'sha256').hexdigest(),
    'purpose':'Temporary readable UI font, not final pixel typography'},
    'sound':{'file':'assets/audio/probe-confirm.wav','source':'Original sine pulse generated by project tool'}}
(ROOT/'docs'/'probe-assets.json').write_text(json.dumps(receipt,indent=2),encoding='utf-8')
print(json.dumps(receipt,indent=2))
